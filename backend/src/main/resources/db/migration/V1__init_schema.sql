-- Explainly schema. Portable across PostgreSQL (production) and H2 in PostgreSQL mode (tests).
-- Structured AI output is stored as JSON text.

CREATE TABLE users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           VARCHAR(320) UNIQUE,
    password_hash   VARCHAR(100),
    display_name    VARCHAR(120) NOT NULL,
    avatar_url      VARCHAR(1024),
    role            VARCHAR(20)  NOT NULL,
    auth_provider   VARCHAR(20)  NOT NULL,
    google_subject  VARCHAR(255) UNIQUE,
    last_login_at   TIMESTAMP WITH TIME ZONE,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE refresh_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash  VARCHAR(64) NOT NULL UNIQUE,
    expires_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked     BOOLEAN NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_refresh_tokens_user ON refresh_tokens (user_id);

CREATE TABLE connected_accounts (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id               BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    provider              VARCHAR(30) NOT NULL,
    provider_account_id   VARCHAR(255),
    account_name          VARCHAR(255),
    access_token_enc      TEXT NOT NULL,
    refresh_token_enc     TEXT,
    token_expires_at      TIMESTAMP WITH TIME ZONE,
    scopes                VARCHAR(1024),
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_connected_accounts_user_provider UNIQUE (user_id, provider)
);

CREATE TABLE videos (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    youtube_id        VARCHAR(11) NOT NULL UNIQUE,
    title             VARCHAR(500) NOT NULL,
    channel_title     VARCHAR(255),
    description       TEXT,
    thumbnail_url     VARCHAR(1024),
    duration_seconds  INTEGER,
    published_at      TIMESTAMP WITH TIME ZONE,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE transcripts (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    video_id       BIGINT NOT NULL REFERENCES videos (id) ON DELETE CASCADE,
    source         VARCHAR(30) NOT NULL,
    language       VARCHAR(20),
    content        TEXT NOT NULL,
    segments_json  TEXT NOT NULL,
    content_hash   VARCHAR(64) NOT NULL,
    submitted_by   BIGINT REFERENCES users (id) ON DELETE SET NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_transcripts_video_hash ON transcripts (video_id, content_hash);

CREATE TABLE video_analyses (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    video_id        BIGINT NOT NULL REFERENCES videos (id) ON DELETE CASCADE,
    transcript_id   BIGINT REFERENCES transcripts (id) ON DELETE SET NULL,
    created_by      BIGINT REFERENCES users (id) ON DELETE SET NULL,
    status          VARCHAR(30) NOT NULL,
    category        VARCHAR(60),
    progress        INTEGER NOT NULL DEFAULT 0,
    status_message  VARCHAR(500),
    error_message   VARCHAR(2000),
    ai_provider     VARCHAR(50),
    ai_model        VARCHAR(100),
    started_at      TIMESTAMP WITH TIME ZONE,
    completed_at    TIMESTAMP WITH TIME ZONE,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_analyses_video ON video_analyses (video_id);
CREATE INDEX idx_analyses_status ON video_analyses (status);
CREATE INDEX idx_analyses_transcript ON video_analyses (transcript_id);

CREATE TABLE explanations (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    analysis_id            BIGINT NOT NULL UNIQUE REFERENCES video_analyses (id) ON DELETE CASCADE,
    overview_json          TEXT NOT NULL,
    beginner_explanation   TEXT,
    technical_explanation  TEXT,
    concepts_json          TEXT,
    summary_short          TEXT,
    summary_medium         TEXT,
    summary_detailed       TEXT,
    generated_notes        TEXT,
    created_at             TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE video_chapters (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    analysis_id           BIGINT NOT NULL REFERENCES video_analyses (id) ON DELETE CASCADE,
    position              INTEGER NOT NULL,
    title                 VARCHAR(500) NOT NULL,
    start_seconds         INTEGER,
    end_seconds           INTEGER,
    short_summary         TEXT,
    simple_explanation    TEXT,
    detailed_explanation  TEXT,
    real_world_example    TEXT,
    practical_use_case    TEXT,
    key_points_json       TEXT,
    concepts_json         TEXT
);
CREATE INDEX idx_chapters_analysis ON video_chapters (analysis_id, position);

CREATE TABLE illustrations (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    analysis_id   BIGINT NOT NULL REFERENCES video_analyses (id) ON DELETE CASCADE,
    chapter_id    BIGINT REFERENCES video_chapters (id) ON DELETE SET NULL,
    position      INTEGER NOT NULL,
    title         VARCHAR(500) NOT NULL,
    diagram_type  VARCHAR(30) NOT NULL,
    explanation   TEXT,
    example       TEXT,
    spec_json     TEXT,
    svg           TEXT,
    image_data    TEXT,
    image_mime    VARCHAR(50),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_illustrations_analysis ON illustrations (analysis_id, position);

CREATE TABLE notes (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    analysis_id  BIGINT NOT NULL REFERENCES video_analyses (id) ON DELETE CASCADE,
    content      TEXT NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_notes_user_analysis UNIQUE (user_id, analysis_id)
);

CREATE TABLE quizzes (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    analysis_id  BIGINT NOT NULL REFERENCES video_analyses (id) ON DELETE CASCADE,
    title        VARCHAR(500) NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_quizzes_analysis ON quizzes (analysis_id);

CREATE TABLE quiz_questions (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id            BIGINT NOT NULL REFERENCES quizzes (id) ON DELETE CASCADE,
    position           INTEGER NOT NULL,
    question_type      VARCHAR(20) NOT NULL,
    question           TEXT NOT NULL,
    code_snippet       TEXT,
    options_json       TEXT NOT NULL,
    correct_index      INTEGER NOT NULL,
    explanation        TEXT,
    timestamp_seconds  INTEGER
);
CREATE INDEX idx_quiz_questions_quiz ON quiz_questions (quiz_id, position);

CREATE TABLE quiz_attempts (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id       BIGINT NOT NULL REFERENCES quizzes (id) ON DELETE CASCADE,
    user_id       BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    score         INTEGER NOT NULL,
    total         INTEGER NOT NULL,
    answers_json  TEXT NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_quiz_attempts_user ON quiz_attempts (user_id, created_at);
CREATE INDEX idx_quiz_attempts_quiz ON quiz_attempts (quiz_id);

CREATE TABLE flashcards (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    analysis_id  BIGINT NOT NULL REFERENCES video_analyses (id) ON DELETE CASCADE,
    position     INTEGER NOT NULL,
    question     TEXT NOT NULL,
    answer       TEXT NOT NULL,
    definition   TEXT,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_flashcards_analysis ON flashcards (analysis_id, position);

CREATE TABLE bookmarks (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    analysis_id        BIGINT NOT NULL REFERENCES video_analyses (id) ON DELETE CASCADE,
    chapter_id         BIGINT REFERENCES video_chapters (id) ON DELETE SET NULL,
    timestamp_seconds  INTEGER,
    title              VARCHAR(500) NOT NULL,
    note               TEXT,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_bookmarks_user ON bookmarks (user_id, created_at);
CREATE INDEX idx_bookmarks_user_analysis ON bookmarks (user_id, analysis_id);

CREATE TABLE learning_history (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                  BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    analysis_id              BIGINT NOT NULL REFERENCES video_analyses (id) ON DELETE CASCADE,
    progress_percent         INTEGER NOT NULL DEFAULT 0,
    completed_chapters_json  TEXT NOT NULL DEFAULT '[]',
    last_position_seconds    INTEGER,
    last_accessed_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at               TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_history_user_analysis UNIQUE (user_id, analysis_id)
);
CREATE INDEX idx_history_user_accessed ON learning_history (user_id, last_accessed_at);

CREATE TABLE chat_messages (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    analysis_id     BIGINT NOT NULL REFERENCES video_analyses (id) ON DELETE CASCADE,
    role            VARCHAR(20) NOT NULL,
    content         TEXT NOT NULL,
    citations_json  TEXT,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_chat_user_analysis ON chat_messages (user_id, analysis_id, created_at);
